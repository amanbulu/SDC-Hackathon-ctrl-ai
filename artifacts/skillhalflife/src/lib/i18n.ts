export function translateFree(lang: Lang, s: string): string {
  if (lang !== 'ms') return s;
  const exact: Record<string,string> = {
    'Year 3 · Bachelor of Software Engineering': 'Tahun 3 · Ijazah Sarjana Muda Kejuruteraan Perisian',
    'Two university projects and a 12-week web development internship': 'Dua projek universiti dan latihan industri pembangunan web selama 12 minggu',
  };
  if (exact[s]) return exact[s];
  return MS_PHRASES.reduce((acc, [re, to]) => acc.replace(re, to), s);
}

